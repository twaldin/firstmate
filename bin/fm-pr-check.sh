#!/usr/bin/env bash
# Record a PR-ready task: appends pr=<url> and GitHub's pr_head=<sha> to
# state/<id>.meta when available, then arms the watcher's PR poll by writing
# state/<id>.check.sh.
# The generated check preserves the watcher check contract: print exactly one
# line when firstmate should wake, and print nothing otherwise.
# It wakes on merge, as before, and also rate-limited reasserts an open PR that
# is approved on the current head and remains unmerged past
# FM_PR_READY_THRESHOLD_SECS.
# Usage: fm-pr-check.sh <task-id> <pr-url>
set -eu

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"
STATE="${FM_STATE_OVERRIDE:-$FM_HOME/state}"
"$FM_ROOT/bin/fm-guard.sh" || true
ID=$1
URL=$2

META="$STATE/$ID.meta"
if [ -f "$META" ]; then
  WT=$(grep '^worktree=' "$META" | tail -1 | cut -d= -f2- || true)
  PR_HEAD=
  if [ -n "$WT" ] && [ -d "$WT" ]; then
    if command -v gh >/dev/null 2>&1; then
      if REMOTE_HEAD=$(cd "$WT" && gh pr view "$URL" --json headRefOid -q .headRefOid 2>/dev/null); then
        PR_HEAD=$REMOTE_HEAD
      fi
    fi
  fi
  if ! grep -qxF "pr=$URL" "$META"; then
    echo "pr=$URL" >> "$META"
  fi
  if [ -n "$PR_HEAD" ] && ! grep -qxF "pr_head=$PR_HEAD" "$META"; then
    echo "pr_head=$PR_HEAD" >> "$META"
  fi
fi

{
  printf 'PR_URL=%q\n' "$URL"
  printf 'PR_TASK_ID=%q\n' "$ID"
  printf 'PR_STATE_DIR=%q\n' "$STATE"
  cat <<'CHECK'
# Generated by bin/fm-pr-check.sh.
# Contract: one stdout line wakes firstmate; no stdout keeps sleeping.
set -u

numeric_or_default() {  # <value> <default>
  case "${1:-}" in
    ''|*[!0-9]*) printf '%s\n' "$2" ;;
    *) printf '%s\n' "$1" ;;
  esac
}

iso_epoch() {  # <github-iso8601>
  local iso=$1 clean epoch
  [ -n "$iso" ] || return 1
  clean=${iso%Z}
  clean=${clean%%.*}Z
  if epoch=$(date -u -j -f '%Y-%m-%dT%H:%M:%SZ' "$clean" '+%s' 2>/dev/null); then
    printf '%s\n' "$epoch"
    return 0
  fi
  if epoch=$(date -u -d "$clean" '+%s' 2>/dev/null); then
    printf '%s\n' "$epoch"
    return 0
  fi
  return 1
}

command -v gh >/dev/null 2>&1 || exit 0

query=$(
  gh pr view "$PR_URL" \
    --json state,headRefOid,reviewDecision,isDraft,latestReviews \
    --jq '
      (.latestReviews // [] | map(select(.state == "APPROVED"))) as $approvals
      | (if ($approvals | length) > 0 then ($approvals | max_by(.submittedAt // "")) else {} end) as $approval
      | [
          (.state // ""),
          (.headRefOid // ""),
          ((.isDraft // false) | tostring),
          (.reviewDecision // ""),
          ($approval.submittedAt // ""),
          ($approval.commit.oid // $approval.commitOid // "")
        ]
      | @tsv
    ' 2>/dev/null
) || exit 0

IFS="$(printf '\t')" read -r state head is_draft review_decision approved_at approved_commit <<EOF_QUERY
$query
EOF_QUERY

case "$state" in
  MERGED|merged) echo "merged"; exit 0 ;;
  OPEN|open) ;;
  *) exit 0 ;;
esac

case "$is_draft" in true|yes) exit 0 ;; esac
case "$review_decision" in APPROVED|approved) ;; *) exit 0 ;; esac

# GitHub may remember an older approval after a final push.
# Only an approval attached to the current head is decision-ready for Tim.
[ -n "${head:-}" ] || exit 0
[ -n "${approved_commit:-}" ] || exit 0
[ "$approved_commit" = "$head" ] || exit 0

approved_epoch=$(iso_epoch "$approved_at") || exit 0
now=$(date '+%s')
age=$((now - approved_epoch))
threshold=$(numeric_or_default "${FM_PR_READY_THRESHOLD_SECS:-14400}" 14400)
repeat=$(numeric_or_default "${FM_PR_READY_REPEAT_SECS:-$threshold}" "$threshold")
[ "$age" -ge "$threshold" ] || exit 0

marker="$PR_STATE_DIR/$PR_TASK_ID.pr-ready-reminded"
approval_key="$head:$approved_at"
last_epoch=0
last_key=
if [ -r "$marker" ]; then
  read -r last_epoch last_key < "$marker" || true
  case "$last_epoch" in ''|*[!0-9]*) last_epoch=0 ;; esac
fi

if [ "$last_key" = "$approval_key" ] && [ $((now - last_epoch)) -lt "$repeat" ]; then
  exit 0
fi

printf '%s\t%s\n' "$now" "$approval_key" > "$marker" 2>/dev/null || true
echo "approved-awaiting-Tim: $PR_URL approved ${age}s ago"
CHECK
} > "$STATE/$ID.check.sh"
echo "armed: state/$ID.check.sh polls $URL"
